#!/usr/bin/env python3
"""Build TABLE.md and leaderboard.csv from rows/*.json. See README.md.

    tools/spiralfiteval/leaderboard/build_table.py

Pure presentation: every number comes from a row written by add_row.py, and the floor flags
are the ones the row computed. Nothing here recomputes a score.
"""

from __future__ import annotations

import csv
import json
import os
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROWS = Path(os.environ.get("LEADERBOARD_ROWS", HERE / "rows"))
FLOOR_LABEL = {"H1": "H1", "H1_ladders": "H1-ladders", "H2": "H2", "H3": "H3"}


def pct(x, nd=1):
    return "-" if x is None else f"{100 * x:.{nd}f}%"


def num(x, nd=2):
    return "-" if x is None else f"{x:.{nd}f}"


def floor_cell(row) -> str:
    fl = row.get("floors") or {}
    if not fl:
        return "n/a"          # the row has no reference metric that could sit at a floor
    if all(v == "not measured" for v in fl.values()):
        return "not measured"
    at, ok, unk = [], [], []
    for k, v in fl.items():
        if not isinstance(v, dict):
            continue
        (at if v["at_floor"] is True else ok if v["at_floor"] is False else unk).append(FLOOR_LABEL.get(k, k))
    if not at and not unk:
        return "none (" + ", ".join(ok) + " beat it)" if ok else "-"
    bits = []
    if at:
        bits.append("**" + ", ".join(at) + " at floor**")
    if unk:
        bits.append(", ".join(unk) + " undetermined")
    return "; ".join(bits)


def sort_key(row):
    h = row["headline"]
    has_h1 = h.get("H1_slips_per_wrap") is not None
    return (0 if has_h1 else 1,
            h.get("H1_slips_per_wrap") if has_h1 else h.get("H5_duplicate", 1.0))


def main():
    rows = sorted((json.loads(p.read_text()) for p in sorted(ROWS.glob("*.json"))), key=sort_key)
    if not rows:
        raise SystemExit("no rows in " + str(ROWS))
    authors = sorted({r["author"] for r in rows if r.get("author")})

    md = []
    md.append("# spiralfiteval leaderboard\n")
    s = "" if len(rows) == 1 else "s"
    md.append(f"{len(rows)} published spiral fit{s} from {len(authors)} "
              f"author{'' if len(authors) == 1 else 's'} ({', '.join(authors)}), all scored by "
              f"`tools/spiralfiteval` at commit `{rows[0]['tool']['commit'][:7]}` of my private "
              "working history (row commit ids do not resolve in this repository; see "
              "[README.md](README.md#provenance-of-a-row)). "
              "Generated by `build_table.py`; do not edit by hand.\n")
    md.append("**Read the floor column first.** A metric marked *at floor* does not beat what the "
              "same references score when they are moved off their sheet, so it says nothing about "
              "that fit and must not be read as a rank. The rule and the metric definitions are in "
              "[README.md](README.md). `held-out H1 = no` means the fit was given the human winding "
              "annotations as an input.\n")
    md.append("Lower is better for every column except H1 exact. `-` means the metric needs "
              "references that are not public for that scroll (H5 needs none); `n/a` in the floor "
              "column means the row has no reference metric that could sit at a floor.\n")
    md.append("Two caveats that apply to H5 on every row: `fit_spiral.py`'s default of 130 "
              "windings exports surplus windings outside the papyrus (villa PR #2048), and that "
              "is where almost all of the Paris 4 duplicates sit, so part of a fit's duplicate "
              "share is the default and not the fit; and a fit's own duplicates are invisible to "
              "the ink-pixel objective it was tuned on (villa PR #1842). Per-winding duplicate "
              "shares are in each row's JSON.\n")
    head = ["#", "fit", "author", "scroll", "band z", "H1 slips/wrap", "H1 exact",
            "H2 /1k vx", "H3 med vx", "H5 dup", "floors", "held-out H1", "cost s / GB"]
    md.append("| " + " | ".join(head) + " |")
    md.append("|" + "---|" * len(head))
    for i, r in enumerate(rows, 1):
        h, c = r["headline"], r["cost"]
        ci = h.get("H1_slips_ci95")
        slips = pct(h.get("H1_slips_per_wrap"))
        if ci:
            slips += f" ({pct(ci[0], 0)}-{pct(ci[1], 0)})"
        ho = {True: "yes", False: "**no**", None: "-"}[r.get("held_out_H1")]
        band = "-" if not r.get("band_z") else f"{r['band_z'][0]}-{r['band_z'][1]}"
        md.append("| " + " | ".join([
            str(i), f"`{r['id']}`", r.get("author") or "-", r.get("scroll") or "-", band,
            slips, pct(h.get("H1_exact")), num(h.get("H2_per_1000_vox")),
            num(h.get("H3_median_vox")), pct(h.get("H5_duplicate"), 2), floor_cell(r), ho,
            f"{c.get('seconds')} / {c.get('peak_rss_gb')}"]) + " |")

    md.append("\n## Per row: command, input, hashes\n")
    md.append("Every row is one command from a fresh clone (see [README.md](README.md#add-your-fit-one-command) "
              "for the venv). `sha256` is of the fit file, or of a sorted `relpath  sha256` manifest "
              "of a mesh folder.\n")
    for i, r in enumerate(rows, 1):
        h = r["headline"]
        md.append(f"### {i}. `{r['id']}`\n")
        md.append(f"- **author** {r.get('author')} — {r.get('author_url') or 'n/a'}"
                  + (f" ({r['release']})" if r.get("release") else ""))
        md.append(f"- **fit** {r.get('format')}, {h['vertices']:,} vertices, "
                  f"w{h['windings'][0]:03d}-w{h['windings'][1]:03d}, grid step "
                  f"{h['grid_step_vox']:.1f} vx; inputs: {r.get('fit_inputs') or 'see the author'}")
        md.append(f"- **fitter** {r.get('fitter') or 'n/a'}")
        md.append(f"- **download** {r.get('fit_url') or 'n/a'}"
                  + (f" @ `{r['fit_commit'][:12]}`" if r.get("fit_commit") else ""))
        ih = r["input_hash"]
        md.append(f"- **input sha256** `{ih['sha256']}` ({ih['kind']}, {ih['files']} file(s), "
                  f"{ih['bytes'] / 2**20:.1f} MiB)")
        md.append(f"- **command** `{r['command']}`")
        md.append(f"- **scores** `{r['score_command']}`")
        md.append(f"- **tool** `{r['tool']['commit']}`"
                  + (" (dirty working tree)" if r["tool"].get("dirty") else "")
                  + f", Python {r['python']}, scored {r['scored_utc']}")
        md.append(f"- **cost** {r['cost'].get('seconds')} s, peak RSS "
                  f"{r['cost'].get('peak_rss_gb')} GB")
        if r.get("published_slips_per_wrap") is not None:
            ci = r.get("published_slips_ci95") or [float("nan")] * 2
            inside = ci[0] <= h["H1_slips_per_wrap"] <= ci[1]
            md.append(f"- **author's own H1** {pct(r['published_slips_per_wrap'])} "
                      f"(95% CI {pct(ci[0], 0)}-{pct(ci[1], 0)}); this tool "
                      f"{pct(h['H1_slips_per_wrap'])} — {'inside' if inside else 'OUTSIDE'} his CI")
        if r.get("note"):
            md.append(f"- **note** {r['note']}")
        fl = r.get("floors") or {}
        for k, v in fl.items():
            if isinstance(v, dict):
                md.append(f"- **floor {FLOOR_LABEL.get(k, k)}** value {v['value']:.4g} vs floor "
                          f"{v['floor_mean']:.4g} (sd {v['floor_sd']:.3g}, {v['floor_used']}): "
                          f"margin {v['margin']:+.4g} = {v['margin_over_sd']:.1f} sd -> "
                          + ("**at floor**" if v["at_floor"] is True else
                             "beats its floor" if v["at_floor"] is False else "undetermined"))
        md.append("")
    md.append("Row JSON (the full score, the floor blocks, the console output): "
              "[rows/](rows/). Numbers in the same units as `tools/spiralfiteval`: "
              "voxels of the fit's own frame.\n")
    (HERE / "TABLE.md").write_text("\n".join(md) + "\n")

    cols = ["id", "author", "scroll", "band_z0", "band_z1", "run", "fit_inputs", "held_out_H1",
            "format", "fit_url", "input_sha256", "tool_commit", "vertices", "windings_lo",
            "windings_hi", "grid_step_vox", "H1_slips_per_wrap", "H1_ci95_lo", "H1_ci95_hi",
            "H1_exact", "H1_adjacent_tests", "H2_per_1000_vox", "H3_median_vox", "H3_within_4",
            "H3_not_on_fit", "H5_duplicate", "H5_median_gap_vox", "H5_area_weighted",
            "published_slips_per_wrap", "floors_at_floor", "floors_beat", "floors_undetermined",
            "seconds", "peak_rss_gb", "command"]
    with open(HERE / "leaderboard.csv", "w", newline="") as f:
        w = csv.DictWriter(f, cols)
        w.writeheader()
        for r in rows:
            h, fl = r["headline"], (r.get("floors") or {})
            ci = h.get("H1_slips_ci95") or [None, None]
            def names(flag):
                return " ".join(FLOOR_LABEL.get(k, k) for k, v in fl.items()
                                if isinstance(v, dict) and v["at_floor"] is flag)
            w.writerow({
                "id": r["id"], "author": r.get("author"), "scroll": r.get("scroll"),
                "band_z0": (r.get("band_z") or [None, None])[0],
                "band_z1": (r.get("band_z") or [None, None])[1],
                "run": r.get("run"), "fit_inputs": r.get("fit_inputs"),
                "held_out_H1": r.get("held_out_H1"), "format": r.get("format"),
                "fit_url": r.get("fit_url"), "input_sha256": r["input_hash"]["sha256"],
                "tool_commit": r["tool"]["commit"], "vertices": h["vertices"],
                "windings_lo": h["windings"][0], "windings_hi": h["windings"][1],
                "grid_step_vox": h["grid_step_vox"],
                "H1_slips_per_wrap": h.get("H1_slips_per_wrap"),
                "H1_ci95_lo": ci[0], "H1_ci95_hi": ci[1], "H1_exact": h.get("H1_exact"),
                "H1_adjacent_tests": h.get("H1_adjacent_tests"),
                "H2_per_1000_vox": h.get("H2_per_1000_vox"), "H3_median_vox": h.get("H3_median_vox"),
                "H3_within_4": h.get("H3_within_4"), "H3_not_on_fit": h.get("H3_not_on_fit"),
                "H5_duplicate": h.get("H5_duplicate"), "H5_median_gap_vox": h.get("H5_median_gap_vox"),
                "H5_area_weighted": h.get("H5_area_weighted"),
                "published_slips_per_wrap": r.get("published_slips_per_wrap"),
                "floors_at_floor": names(True), "floors_beat": names(False),
                "floors_undetermined": names(None),
                "seconds": r["cost"].get("seconds"), "peak_rss_gb": r["cost"].get("peak_rss_gb"),
                "command": r["command"]})
    print(f"TABLE.md and leaderboard.csv: {len(rows)} rows, {len(authors)} authors")


if __name__ == "__main__":
    main()
